using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text.Json;
using System.Text.RegularExpressions;
using StageGame;
using UnityEngine;
using UnityEngine.UI;

static partial class Program
{
    const string ProgressKey = "stagegame.progress.v1";
    static string OneString(string ko, string en) => JsonSerializer.Serialize(new {
        schemaVersion = 1, strings = new[] { new { key = "test", ko, en } }
    });
    static void ExpectException<T>(Action action, string label) where T : Exception
    {
        try { action(); }
        catch (T) { assertions++; return; }
        throw new Exception(label + " did not throw " + typeof(T).Name);
    }
    static void RunLocalization(string[] args)
    {
        string evidence = Path.GetDirectoryName(args[0]);
        string inputs = Path.Combine(evidence, "AuditInputs");
        using var catalog = JsonDocument.Parse(ActualStringsJson);
        var rows = catalog.RootElement.GetProperty("strings").EnumerateArray()
            .ToDictionary(r => r.GetProperty("key").GetString());

        Run("l10n.catalog_123_and_bilingual_lookup", "actual StringTable; JSON double", () =>
        {
            Check(rows.Count == 123, "expected 123 distinct translations");
            var table = new StringTable(ActualStringsJson);
            foreach (string locale in new[] { "ko", "en", "ko" })
            {
                table.SetLanguage(locale);
                foreach (var pair in rows)
                {
                    Check(pair.Value.EnumerateObject().Select(p => p.Name).OrderBy(n => n)
                        .SequenceEqual(new[] { "en", "key", "ko" }), "unexpected exported fields: " + pair.Key);
                    string expected = pair.Value.GetProperty(locale).GetString();
                    Check(!string.IsNullOrWhiteSpace(expected) && table.Text(pair.Key) == expected,
                        "lookup differs from exported " + locale + ": " + pair.Key);
                }
            }
            Check(File.ReadAllBytes(Path.Combine(args[1], "strings.json"))
                .SequenceEqual(File.ReadAllBytes(Path.Combine(args[2], "strings.json"))), "Client/Generated bytes differ");
        });
        Run("l10n.previous_58_and_requested_ui_70_separation", "independent JSON comparison", () =>
        {
            using var baseline = JsonDocument.Parse(File.ReadAllText(Path.Combine(inputs, "previous-strings.json")));
            using var request = JsonDocument.Parse(File.ReadAllText(Path.Combine(inputs, "localization-request.json")));
            var old = baseline.RootElement.GetProperty("strings").EnumerateArray().ToArray();
            var requested = request.RootElement.GetProperty("strings").EnumerateArray().ToArray();
            Check(old.Length == 58 && requested.Length == 70, "baseline/request row count changed");
            var oldKeys = new HashSet<string>(old.Select(r => r.GetProperty("key").GetString()));
            foreach (var row in old)
            {
                string key = row.GetProperty("key").GetString();
                Check(rows.ContainsKey(key) && rows[key].GetProperty("ko").GetString() == row.GetProperty("ko").GetString(),
                    "existing Korean was overwritten: " + key);
            }
            Check(requested.Count(r => !oldKeys.Contains(r.GetProperty("key").GetString())) == 65, "new UI key count");
            foreach (var row in requested)
            {
                string key = row.GetProperty("key").GetString();
                Check(rows.ContainsKey(key), "missing requested UI key: " + key);
                foreach (string locale in new[] { "ko", "en" })
                    Check(rows[key].GetProperty(locale).GetString() == row.GetProperty(locale).GetString(), "requested copy mismatch: " + key);
                object[] formatArgs = Enumerable.Range(0, row.GetProperty("formatArgCount").GetInt32()).Select(i => (object)(i + 41)).ToArray();
                var table = new StringTable(ActualStringsJson);
                foreach (string locale in new[] { "ko", "en" })
                {
                    table.SetLanguage(locale);
                    string expected = string.Format(CultureInfo.InvariantCulture, row.GetProperty(locale).GetString(), formatArgs);
                    Check(table.Format(key, formatArgs) == expected, "UI format request: " + key);
                }
            }
            Check(rows["ui_start"].GetProperty("ko").GetString() == "시작하기", "legacy start key changed");
            Check(rows["client_ui_start"].GetProperty("ko").GetString() == "대국 시작", "revised start not separate");
        });
        Run("l10n.missing_duplicate_empty_and_schema_rejected", "actual StringTable; JSON double", () =>
        {
            foreach (string json in new[] {
                "null", "{}", "{\"schemaVersion\":2,\"strings\":[]}", "{\"schemaVersion\":1,\"strings\":[]}",
                "{\"schemaVersion\":1,\"strings\":[null]}",
                "{\"schemaVersion\":1,\"strings\":[{\"key\":\"test\",\"ko\":\"한국어\"}]}",
                "{\"schemaVersion\":1,\"strings\":[{\"key\":\" \",\"ko\":\"가\",\"en\":\"A\"}]}",
                "{\"schemaVersion\":1,\"strings\":[{\"key\":\"test\",\"ko\":\"가\",\"en\":\"A\"},{\"key\":\"test\",\"ko\":\"나\",\"en\":\"B\"}]}"
            }) Reject(() => new StringTable(json), "invalid string table");
            foreach (string empty in new[] { null, "", " \t" })
            {
                Reject(() => new StringTable(OneString(empty, "English")), "empty Korean");
                Reject(() => new StringTable(OneString("한국어", empty)), "empty English");
            }
            var table = new StringTable(OneString("한국어", "English"));
            Check(!table.Contains("missing") && !table.Contains(null), "missing-key presence");
            ExpectException<KeyNotFoundException>(() => table.Text("missing"), "missing UI key");
        });
        Run("l10n.format_syntax_reordering_literals_and_argument_errors", "actual StringTable; framework formatting", () =>
        {
            var table = new StringTable(OneString("{0}/{1}/{0}", "{1}/{0}/{1}"));
            Check(table.Format("test", "A", "B") == "A/B/A", "Korean repeated arguments");
            table.SetLanguage("en");
            Check(table.Format("test", "A", "B") == "B/A/B", "English reordered arguments");
            ExpectException<FormatException>(() => table.Format("test", "A"), "missing caller argument");
            var braces = new StringTable(OneString("{{{0}}} {{name}}", "{{{0}}} {{name}}"));
            Check(braces.Format("test", "X") == "{X} {name}", "escaped literal braces");
            foreach (string invalid in new[] { "{", "}", "{0", "0}", "{name}", "{0:00}", "{0,3}", "{-1}", "{1}", "{0}{2}", "{{{0}}", "{999999999999999999999}" })
            {
                Reject(() => new StringTable(OneString(invalid, invalid)), "format " + invalid);
                Reject(() => new StringTable(OneString("Good", invalid)), "English format " + invalid);
            }
            Reject(() => new StringTable(OneString("{0}", "none")), "different argument sets");
        });
        Run("l10n.legacy_unknown_locale_and_saved_language_restore", "actual progress; memory PlayerPrefs/JSON double", () =>
        {
            string legacy = "{\"saveVersion\":1,\"unlockedStage\":7,\"completedMatches\":9,\"lastInterstitialMatch\":4,\"lastInterstitialUtc\":90,\"soundEnabled\":false,\"processedMatchIds\":[\"legacy\"]}";
            foreach (string locale in new[] { null, "", "EN", "en-US", "ja", " ko ", "en", "ko" })
            {
                PlayerPrefs.Reset();
                string json = locale == null ? legacy : legacy.Substring(0, legacy.Length - 1) + ",\"language\":" + JsonSerializer.Serialize(locale) + "}";
                PlayerPrefs.SetString(ProgressKey, json);
                var p = new ProgressStore(30);
                string expected = locale == "en" ? "en" : "ko";
                Check(p.Data.language == expected && p.LoadWarning == null, "legacy/unknown locale " + locale);
                Check(p.Data.unlockedStage == 7 && p.Data.completedMatches == 9 && !p.Data.soundEnabled && p.Data.lastInterstitialMatch == 4 && p.Data.lastInterstitialUtc == 90, "locale migration changed progress");
                Check(!p.RecordResult("legacy", 1, true, 30), "migration lost duplicate protection");
                p.Data.language = "en"; Check(p.Save(), "save English");
                var reload = new ProgressStore(30);
                Check(reload.Data.language == "en" && reload.Data.unlockedStage == 7 && !reload.Data.soundEnabled, "English restore");
            }
            PlayerPrefs.SetString(ProgressKey, legacy.Substring(0, legacy.Length - 1) + ",\"language\":null}");
            Check(new ProgressStore(30).Data.language == "ko", "explicit null locale");
        });
        Run("l10n.warning_keys_localized_and_save_failure_nonfatal", "actual progress/StringTable; persistence double", () =>
        {
            PlayerPrefs.Reset(); PlayerPrefs.SetString(ProgressKey, "{broken");
            var progress = new ProgressStore(30);
            Check(progress.LoadWarning == "error_load", "load warning not a stable key");
            PlayerPrefs.ThrowOnSave = true;
            Check(!progress.Save() && progress.SaveWarning == "client_error_save", "save warning key/failure");
            PlayerPrefs.ThrowOnSave = false;
            var table = new StringTable(ActualStringsJson);
            foreach (string locale in new[] { "ko", "en" })
            {
                table.SetLanguage(locale);
                foreach (string key in new[] { progress.LoadWarning, progress.SaveWarning, new NoFillAds().Status })
                    Check(table.Text(key) == rows[key].GetProperty(locale).GetString() && table.Text(key) != key, "untranslated warning " + key);
            }
            Check(progress.Save() && progress.SaveWarning == null, "successful save must clear stale failure");
        });
        Run("l10n.literal_ui_key_references_exist", "static source/data check; not prefab execution", () =>
        {
            string app = File.ReadAllText(Path.Combine(evidence, "Sources", "GameApp.cs"));
            var keys = Regex.Matches(app, "\\b(?:T|F|SetMatchNotice)\\(\"([^\"]+)\"").Cast<Match>().Select(m => m.Groups[1].Value).Distinct().ToArray();
            Check(keys.Length > 10, "UI key coverage unexpectedly empty");
            foreach (string key in keys) Check(rows.ContainsKey(key), "missing literal UI key " + key);
        });
        Run("l10n.app_switch_same_match_and_relaunch", "actual GameApp; UI/coroutine/persistence doubles", () =>
        {
            var app = MakeApp();
            app.localizedLabels = new[] { new LocalizedLabel { target = new Text(), key = "ui_settings" }, new LocalizedLabel { target = new Text(), key = "client_game_title" } };
            Set(app, "board", Replay(new[] { 3, 2 }));
            var gate = (RewardGate)Get(app, "rewardGate"); gate.TryBegin(out int token); gate.Complete(token, AdResult.Completed);
            string before = BoardState((ConnectFourBoard)Get(app, "board"));
            string matchId = (string)Get(app, "matchId");
            var progress = (ProgressStore)Get(app, "progress"); progress.Data.soundEnabled = false;
            foreach (string locale in new[] { "en", "ko", "en" })
            {
                app.SetLanguage(locale);
                Check(BoardState((ConnectFourBoard)Get(app, "board")) == before && (string)Get(app, "matchId") == matchId, "language reset current match");
                Check(ReferenceEquals(gate, Get(app, "rewardGate")) && gate.Granted && !app.hint.interactable, "language restored used hint");
                Check(progress.Data.completedMatches == 0 && !progress.Data.soundEnabled && app.match.activeSelf, "language changed progression/sound/screen");
                Check(app.turnLabel.text == rows["client_ui_player_turn"].GetProperty(locale).GetString(), "turn text not switched");
                Check(app.localizedLabels[0].target.text == rows["ui_settings"].GetProperty(locale).GetString(), "static label not switched");
                Check(app.hintLabel.text == rows["client_hint_used"].GetProperty(locale).GetString(), "used hint text not switched");
                Check(app.stoneLabels[3].text == rows["player_stone"].GetProperty(locale).GetString(), "stone label not switched");
            }
            var restart = MakeApp(false);
            Check(((ProgressStore)Get(restart, "progress")).Data.language == "en" && !((ProgressStore)Get(restart, "progress")).Data.soundEnabled, "language/sound not restored by startup");
            Check(restart.playLabel.text == rows["client_ui_start"].GetProperty("en").GetString(), "startup English not applied");
            restart.SetLanguage("unknown");
            Check(restart.playLabel.text == rows["client_ui_start"].GetProperty("ko").GetString(), "runtime unknown locale fallback");
        });
    }
}
